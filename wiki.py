WIKI_CLC = """
BASES GENERALES — CAMBRIDGE LEAGUE (CLC)

1. DE LA ORGANIZACIÓN

El torneo de padres de familia del Colegio Cambridge College Lima ("CCL") tiene
como objetivo principal fomentar la amistad, la camaradería y promover la
práctica deportiva entre los padres de familia, desde Stage 2 hasta 5 Form.

La organización, planificación, ejecución y supervisión del torneo está a cargo
del Cambridge College Lima, en coordinación con la Asesoría de Deportes (ASPAFA)
y con el respaldo logístico de las respectivas Asociaciones de Padres de Familia
("LOS ORGANIZADORES").

1.3. Toda comunicación formal entre los delegados de los equipos y LOS
ORGANIZADORES deberá realizarse únicamente al correo o WhatsApp de contacto
oficial.
1.4. El torneo está compuesto por diez (10) equipos, distribuidos en dos (2)
grupos de cinco (5) equipos cada uno.
1.5. Todos los participantes deben cumplir estrictamente con las disposiciones
de estas Bases Generales durante todo el desarrollo del campeonato.
1.6. El campeonato se lleva a cabo en las instalaciones del CCL.
1.7. Se conforman dos comisiones: el Comité de Justicia y el Comité
Organizador, integradas por el Delegado Fútbol 8 de ASPAFA CCL, el organizador
del torneo, el coordinador de arbitraje/planillero, y un veedor.
1.8. Beneficios del torneo: entrega de balones reglamentarios, premiación con
copas/trofeos/medallas, y reconocimientos grupales e individuales.

2. DE LAS INSCRIPCIONES

2.1. Cada jugador debe identificarse con DNI, Carné de Extranjería, Licencia de
Conducir o Pasaporte, exigible en cualquier etapa del campeonato.
2.2. Los equipos elaboran planillas oficiales con los nombres ya impresos,
entregadas al inicio de cada partido y firmadas por el delegado.
2.3. Cada equipo inscribe un delegado oficial; en caso de inasistencia, debe
designar un subdelegado.
2.4. Para inscribir al equipo se envía nombre completo, DNI y número de
camiseta de cada jugador.
2.5. Se permiten nuevas incorporaciones solo hasta la última fecha de la fase
de grupos — no hay modificaciones durante las fases finales.
2.6. Los jugadores participan bajo su entera responsabilidad; ni LOS
ORGANIZADORES, ni el CCL, ni la ASPAFA asumen gastos médicos o de traslado más
allá de los primeros auxilios en cancha.
2.8. Solo pueden inscribirse padres o tutores legales del grado en que están
matriculados sus hijos — no se aceptan refuerzos externos, salvo excepción
evaluada por el Comité de Justicia.
2.9. Padres con hijos en más de un grado tienen tres opciones:
  A) Participar con una sola promoción durante todo el campeonato.
  B) Jugar con más de una promoción eligiendo una como principal; en fases
     eliminatorias solo continúan con la principal, salvo que la secundaria
     avance y sea indispensable para completar el mínimo de 10 jugadores.
  C) Los equipos clasificados a la segunda fase pueden incorporar hasta dos
     (02) refuerzos de equipos ya eliminados, siempre que ese jugador haya
     jugado exclusivamente para un solo equipo en la fase de clasificación.

3. DE LOS DELEGADOS

3.1. Cada equipo designa un (01) delegado oficial, único autorizado para
representar al equipo, firmar planillas y presentar reclamos formales.
3.2. Si el delegado quiere jugar o no puede asistir, debe designar con
anticipación a un subdelegado.
3.3. El delegado debe presentarse en mesa de control con 10 minutos de
anticipación, con la lista de jugadores cotejada con camiseta y documento.
3.6. Cualquier reclamo se presenta por escrito en la planilla del partido,
dentro de los 15 minutos posteriores a la culminación del juego. El Comité de
Justicia resuelve en máximo 3 días hábiles, de forma inapelable.
3.7. El delegado puede solicitar, antes o después de un partido, la
verificación de la ficha de inscripción de jugadores del equipo rival.
3.8. Sin delegado o subdelegado notificado con 12 horas de anticipación, el
equipo no puede presentar reclamos.
3.9. El delegado es responsable del comportamiento de jugadores, comando
técnico y barra de su equipo.

4. DE LAS SANCIONES

4.1. Las sanciones las determina exclusivamente el Comité de Justicia (CJ), de
forma inapelable.
4.2. Agresión física a árbitro, personal o participante: expulsión inmediata
del torneo, pudiendo extenderse a futuras ediciones. Agresión verbal: el CJ
evalúa la gravedad según informe arbitral.
4.3. Alinear a un jugador no inscrito, suspendido o sancionado: pierde el
partido por walkover (W.O.). Reincidencia o falsificación: expulsión del
campeonato y partidos dados por perdidos 3-0.
4.4. Tarjeta roja: abandono inmediato del campo y no puede jugar el siguiente
partido; el CJ puede aumentar la sanción según gravedad, incluso fuera del
campo (banca, barra).
4.6. Tarjetas amarillas, fase de grupos: 3 amarillas en partidos distintos
= suspensión de un partido. El conteo se reinicia al empezar la fase
eliminatoria. Doble amarilla en un mismo partido: no juega el siguiente
partido con ESE equipo (si el jugador participa en más de uno).
4.7. Permanencia en el campo: solo jugadores en planilla, delegado y técnico
designado. Sanciones progresivas si alguien más no se retira: 1ª llamada =
amarilla al capitán + falta directa a 12m en contra; 2ª llamada = expulsión
del capitán + penal en contra; 3ª llamada = partido suspendido, W.O. 3-0 en
contra.
4.7.4. Expulsión por agresión física o incitar a pelea: suspensión automática
de dos fechas, y no puede jugar por ningún otro equipo durante el torneo.

5. REGLAMENTACIÓN

5.1. Se rige por las reglas FIFA adaptadas a Fútbol 8: SIN regla de offside,
cambios ilimitados por partido.
5.3. Mínimo 5 jugadores por equipo en cancha para iniciar un partido.
5.4. Prohibido ingerir alcohol antes/durante/después de los partidos, dentro
de las instalaciones del CCL — sanción incluye suspensión del partido en curso.
5.5. Cada partido: dos tiempos de 25 minutos continuos, descanso de 5 minutos.
5.6-5.7. Tolerancia de 5 minutos tras la hora programada; superado, W.O. desde
el minuto 6, marcador 3-0 a favor del equipo presente (o ambos si ninguno
llega).
5.8. Shoot Out (definición por infracciones acumuladas): a partir de la 6ª
falta de un equipo se cobra Shoot Out en vez de continuar jugando. El ejecutor
tiene 7 segundos para rematar desde la línea de cobro; puede ser ayudado por
compañeros, el arquero defiende con ayuda de su equipo. Se puede usar dos
veces consecutivas, luego se reinicia el conteo de faltas (no acumulable entre
tiempos).
5.9. Puntuación: victoria 3 puntos, empate 1 punto, derrota 0 puntos.
5.10. W.O.: equipo ganador 3 puntos y 3 goles a favor; equipo perdedor 0 puntos
y 3 goles en contra.
5.11. Si un equipo queda con menos de 6 jugadores en cancha, el partido termina
y se adjudica W.O. al rival (salvo que el marcador ya sea más amplio a favor
del rival, en cuyo caso se mantiene ese resultado).
5.12. Dos W.O. de un mismo equipo: eliminación automática del campeonato;
partidos pendientes se dan por ganados 3-0 a los rivales, más sanción del CJ.
5.13. Pierde por W.O. el equipo que: abandone el campo antes de finalizar el
tiempo reglamentario, no presente documentos de identidad a tiempo, o incluya
a un jugador inhabilitado/no inscrito.
5.14. Sustituciones ilimitadas con reingreso permitido, siempre a través de la
mesa técnica y autorización del árbitro — ingreso sin autorización se sanciona
con amarilla.
5.15. Gresca o pelea entre 2+ jugadores: expulsión inmediata de los
involucrados; el CJ evalúa sanción posterior (puede incluir expulsión
definitiva del campeonato).
5.16. Saques laterales con ambas manos; tiros de esquina con el pie.
5.17. Expulsión: abandono inmediato del campo, inhabilitado para el siguiente
partido; el CJ puede imponer sanciones adicionales según gravedad.
5.18. Desempate en fase de grupos, en orden: (1) diferencia de goles,
(2) goles a favor, (3) resultado entre los equipos empatados, (4) menos
tarjetas rojas, (5) menos tarjetas amarillas, (6) sorteo con el Comité
Organizador y delegados presentes.
5.19. Desempate en fases finales: tanda de 3 penales por equipo; si persiste
el empate, penales alternos hasta definir ganador.
5.20. Acumulación de 3 amarillas: suspensión automática para el siguiente
partido, aplicable incluso en la primera fecha de instancias finales. El
conteo se reinicia al iniciar la fase eliminatoria.
5.22. Indumentaria obligatoria: canilleras y medias largas — quien no cumpla
debe abandonar el campo hasta corregirlo, reingresando por el procedimiento
normal de sustituciones.
5.23. Calzado: prohibidos los chimpunes/toperoles altos por riesgo de
lesiones; se recomienda calzado de cocos bajos.
5.24. Los árbitros sancionan todo juego temerario o violento — el torneo
prioriza la confraternidad, no se tolera fuerza desmedida o intencional.

6. FIXTURE Y CASOS NO PREVISTOS

6.3. La estructura final del campeonato se define por sorteo en reunión con
todos los delegados.
6.4. Los grupos definidos por sorteo tienen una cabeza de grupo por serie,
determinada por criterios previamente establecidos (rendimiento, sorteo
previo, etc.).
6.5. Todos los jugadores deben presentarse uniformados con numeración visible,
coincidente con la enviada a los organizadores (o actualizada en mesa antes
del partido).
6.6. Cualquier situación no contemplada en este reglamento se resuelve
conforme a las normas FIFA, evaluada por el Comité de Justicia y el Comité
Organizador.
6.7. El Comité Organizador no se responsabiliza por pérdida de objetos
personales antes, durante o después de los partidos.
"""


